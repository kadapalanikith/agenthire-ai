import { useState } from 'react';
import { Pressable, View } from 'react-native';
import { useLocalSearchParams } from 'expo-router';
import { ChevronDown, ChevronUp, Code2, Timer } from 'lucide-react-native';
import { Badge, Card, CardHeader, Chip, EmptyState, ErrorState, Screen, ScreenHeader, Skeleton, Text } from '../../../../../src/components/ui';
import { useWorkflow } from '../../../../../src/features/workflows/hooks';
import { useTheme } from '../../../../../src/theme/ThemeProvider';

const LEVEL_LABELS = { does_not_meet: 'Does not meet', partially_meets: 'Partially meets', meets: 'Meets', exceeds: 'Exceeds' };
const levelLabel = (l) => LEVEL_LABELS[l] || l.replace(/_/g, ' ');

function Rubric({ rubric, levels }) {
  return (
    <View className="mt-2 gap-1.5 rounded-xl bg-surface-muted p-3">
      {levels.map((l) => (
        <View key={l} className="gap-0.5">
          <Text variant="caption" className="font-semibold uppercase tracking-wide">
            {levelLabel(l)}
          </Text>
          <Text variant="label" tone="muted" className="font-normal">
            {rubric[l]}
          </Text>
        </View>
      ))}
    </View>
  );
}

function Expandable({ title, meta, children, testID }) {
  const { colors } = useTheme();
  const [open, setOpen] = useState(false);
  return (
    <View className="border-b border-border py-3" testID={testID}>
      <Pressable accessibilityRole="button" accessibilityState={{ expanded: open }} onPress={() => setOpen((o) => !o)} className="flex-row gap-3">
        <View className="flex-1 gap-1">
          <Text className="font-medium">{title}</Text>
          {meta}
        </View>
        {open ? <ChevronUp size={18} color={colors.muted} /> : <ChevronDown size={18} color={colors.muted} />}
      </Pressable>
      {open ? children : null}
    </View>
  );
}

/** Interview questions, coding tasks and rubrics generated by the Interview Agent. */
export default function InterviewKitScreen() {
  const { workflowId } = useLocalSearchParams();
  const { colors } = useTheme();
  const query = useWorkflow(workflowId);
  const backHref = `/dashboard/workflows/${workflowId}`;

  if (query.isPending) {
    return (
      <Screen edges={['top']}>
        <ScreenHeader fallbackHref={backHref} />
        <Skeleton className="h-64 w-full rounded-2xl" />
      </Screen>
    );
  }
  if (query.isError) {
    return (
      <Screen edges={['top']}>
        <ScreenHeader fallbackHref={backHref} />
        <ErrorState error={query.error} onRetry={query.refetch} />
      </Screen>
    );
  }

  const kit = query.data.state_output?.interview_agent;
  if (!kit) {
    return (
      <Screen edges={['top']}>
        <ScreenHeader title="Interview kit" fallbackHref={backHref} />
        <EmptyState
          title="No interview kit"
          description={
            query.data.nodes.find((n) => n.name === 'interview_agent')?.status === 'skipped'
              ? 'The candidate was rejected, so no interview kit was generated.'
              : 'The kit is generated after the candidate is approved.'
          }
        />
      </Screen>
    );
  }

  const levels = kit.rubric_levels;
  return (
    <Screen edges={['top']}>
      <ScreenHeader
        title="Interview kit"
        subtitle={`${query.data.candidate?.name} · ${query.data.job?.title} · ${kit.interview_rounds} round${kit.interview_rounds === 1 ? '' : 's'}`}
        fallbackHref={backHref}
      />
      <View className="gap-5">
        <View className="flex-row flex-wrap gap-2">
          <Badge label={kit.source === 'llm' ? `AI-generated${kit.llm?.provider ? ` (${kit.llm.provider})` : ''}` : 'Template-based'} tone={kit.source === 'llm' ? 'primary' : 'neutral'} testID="kit-source" />
          {kit.removed_questions?.length ? <Badge label={`${kit.removed_questions.length} question(s) removed by fairness check`} tone="warning" /> : null}
        </View>

        {kit.focus_areas?.length ? (
          <Card>
            <CardHeader title="Focus areas" />
            {kit.focus_areas.map((f) => (
              <Text key={f} tone="muted" className="py-0.5">
                • {f}
              </Text>
            ))}
          </Card>
        ) : null}

        <Card testID="kit-questions">
          <CardHeader title={`Questions (${kit.questions.length})`} subtitle="Tap a question to see its scoring rubric." />
          {kit.questions.map((q, i) => (
            <Expandable
              key={q.id}
              testID={`question-${q.id}`}
              title={`${i + 1}. ${q.question}`}
              meta={
                <View className="flex-row gap-1.5">
                  <Chip label={q.type} />
                  <Chip label={q.skill} tone="primary" />
                </View>
              }
            >
              <Rubric rubric={q.rubric} levels={levels} />
            </Expandable>
          ))}
        </Card>

        <Card testID="kit-tasks">
          <CardHeader title={`Coding tasks (${kit.coding_tasks.length})`} />
          {kit.coding_tasks.length ? (
            kit.coding_tasks.map((t) => (
              <Expandable
                key={t.id}
                testID={`task-${t.id}`}
                title={t.title}
                meta={
                  <View className="flex-row items-center gap-3">
                    <View className="flex-row items-center gap-1">
                      <Timer size={13} color={colors.muted} />
                      <Text variant="caption" tone="muted">
                        {t.time_minutes} min
                      </Text>
                    </View>
                    <View className="flex-row items-center gap-1">
                      <Code2 size={13} color={colors.muted} />
                      <Text variant="caption" tone="muted">
                        {t.skills.join(', ')}
                      </Text>
                    </View>
                  </View>
                }
              >
                <Text tone="muted" className="mt-2" selectable>
                  {t.prompt}
                </Text>
                <Rubric rubric={t.rubric} levels={levels} />
              </Expandable>
            ))
          ) : (
            <Text tone="subtle">No coding tasks for this role.</Text>
          )}
        </Card>

        {kit.guidelines?.length ? (
          <Text variant="caption" tone="subtle">
            Based on: {kit.guidelines.map((g) => g.doc_path.split('/').pop()).join(', ')} · spec v{kit.spec_version}
          </Text>
        ) : null}
      </View>
    </Screen>
  );
}
